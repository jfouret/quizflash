from fastapi.testclient import TestClient

STATIC = pathlib.Path(__file__).resolve().parent.parent / "app" / "static"


def test_brand_assets_are_served(client: TestClient) -> None:
    assert client.get("/favicon.ico").status_code == 200
    assert client.get("/favicon.ico").headers["content-type"] == "image/x-icon"
    assert client.get("/static/favicon.svg").status_code == 200
    assert client.get("/static/icons.svg").status_code == 200
    manifest = client.get("/static/site.webmanifest")
    assert manifest.status_code == 200
    assert json.loads(manifest.text)["short_name"] == "QuizDeck"


def test_stylesheet_is_the_built_design_system(client: TestClient) -> None:
    """style.css is generated by scripts/build-css.sh: a missing build ships nothing."""
    response = client.get("/static/style.css")

    assert response.status_code == 200
    assert "--color-canvas" in response.text
    # The old framework is gone: no page may depend on its variables again.
    assert "--pico-" not in response.text


